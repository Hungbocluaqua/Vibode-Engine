inline bool isKnownCommandLineOption(std::string_view option) {
    return std::find(kKnownCommandLineOptions.begin(), kKnownCommandLineOptions.end(), option) !=
        kKnownCommandLineOptions.end();
}

inline uint32_t commandLineOptionArity(std::string_view option) {
    if (std::find(kFlagOnlyCommandLineOptions.begin(), kFlagOnlyCommandLineOptions.end(), option) !=
        kFlagOnlyCommandLineOptions.end()) {
        return 0u;
    }
    return std::find(kTwoValueCommandLineOptions.begin(), kTwoValueCommandLineOptions.end(), option) !=
        kTwoValueCommandLineOptions.end() ? 2u : 1u;
}

inline void validateCommandLineArguments(int argc, char* const* argv) {
    for (int index = 1; index < argc; ++index) {
        const std::string_view option(argv[index]);
        if (!isKnownCommandLineOption(option)) {
            throw std::runtime_error("Unknown command-line argument: " + std::string(option));
        }
        const uint32_t arity = commandLineOptionArity(option);
        if (index + static_cast<int>(arity) >= argc) {
            throw std::runtime_error("Missing value for command-line argument: " + std::string(option));
        }
        for (uint32_t valueIndex = 1u; valueIndex <= arity; ++valueIndex) {
            const std::string_view value(argv[index + static_cast<int>(valueIndex)]);
            if (value.starts_with("--")) {
                throw std::runtime_error("Missing value for command-line argument: " + std::string(option));
            }
        }
        index += static_cast<int>(arity);
    }
}

